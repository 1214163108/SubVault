"""Build src/lib/psl-data.js from the full Public Suffix List.

Usage:
    python tools/build-psl.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "psl.dat"
TARGET = ROOT / "src" / "lib" / "psl-data.js"


def encode_label(label: str) -> str:
    try:
        return label.encode("idna").decode("ascii")
    except UnicodeError:
        return label


def encode_rule(rule: str) -> str:
    prefix = ""
    if rule.startswith("!"):
        prefix = "!"
        rule = rule[1:]
    elif rule.startswith("*."):
        prefix = "*."
        rule = rule[2:]
    labels = [encode_label(label.lower()) for label in rule.split(".") if label]
    if not labels:
        return ""
    return prefix + ".".join(labels)


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8")
    rules = []
    seen = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rule = encode_rule(line)
        if not rule or rule in seen:
            continue
        seen.add(rule)
        rules.append(rule)

    rules.sort()
    payload = json.dumps(rules, ensure_ascii=False, separators=(",", ":"))
    module = f"""/**
 * Generated from the Public Suffix List.
 * Source: https://publicsuffix.org/list/public_suffix_list.dat
 * Generated by tools/build-psl.py. Do not edit manually.
 * Rules include ICANN and private sections; exceptions keep the leading '!'
 * and wildcard rules keep the leading '*.'.
 */
export const PSL_RULES = new Set({payload});
"""
    TARGET.write_text(module, encoding="utf-8")
    print(f"wrote {TARGET} ({len(rules)} rules, {TARGET.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
